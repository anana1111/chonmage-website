// The date this page was last regenerated for, from its JSON-LD (used for the sitemap lastmod).
export function pageDate(file = OUT) {
  try { return fs.readFileSync(file, 'utf8').match(/"dateModified": "(\d{4}-\d{2}-\d{2})"/)?.[1] || ''; } catch { return ''; }
}

export function generate(now = new Date()) {
  const today = tokyoDate(now);
  let html;
  try {
    const week = checkWeek(readJson('data/week.json'));
    let events = null;
    try { events = usableEvents(readJson('data/events.json')); } catch {}
    if (!events) console.log('::warning::schedule/: data/events.json not usable; today comes from data/week.json.');
    html = pageHtml({ week, events, today });
  } catch (error) {
    // Never replace the last good page with an empty or broken one.
    console.log('::warning::schedule/: kept the previous page: ' + error.message);
    return false;
  }
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (old === html) { console.log('schedule/: no changes.'); return false; }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const tmp = OUT + '.tmp';
  fs.writeFileSync(tmp, html);
  fs.renameSync(tmp, OUT);
  console.log('schedule/: written for ' + today + '.');
  return true;
}

if (import.meta.url === new URL('file://' + process.argv[1]).href) {
  const at = process.argv.indexOf('--now');
  generate(at > 0 ? new Date(process.argv[at + 1]) : new Date());
}
