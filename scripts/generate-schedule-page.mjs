// Generate /schedule/index.html: today's games and the rest of this week as plain HTML, so
// search engines and AI tools that do not run JavaScript can read dates, times and prices.
// Sources: data/events.json for today (it follows the daily X post) and data/week.json (the
// Sunday week picture) for the other days. It lists today and the next 6 dates; days already
// over are left out, so an old week is never shown as current, and a date the week picture
// does not cover yet says so. Run by the daily workflow before generate-news-pages.mjs, which
// reads this page's dateModified for the sitemap lastmod.
// If the data cannot be read or fails the checks, the previous page is kept unchanged.
// Usage: node scripts/generate-schedule-page.mjs [--now 2026-10-16T12:00:00+09:00]
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SITE = 'https://chonmagepoker.com/';
const PAGE_URL = SITE + 'schedule/';
const OUT = path.join(ROOT, 'schedule', 'index.html');
const X_URL = 'https://x.com/ChonmageNiigata';
export const GENERATED_MARKER = '<!-- generated by scripts/generate-schedule-page.mjs -->';

const DAYS_SHOWN = 7;
const TIME = /^(?:[01]\d|2[0-3]):[0-5]\d$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;
const FACT_LABELS = { 'ENTRY': '参加費', 'RE-ENTRY': '再エントリー', 'LATE REG': '最終受付' };

function escapeHtml(value = '') {
  return String(value)
    .replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;').replaceAll("'", '&#39;');
}

export function tokyoDate(now = new Date()) {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Tokyo', year: 'numeric', month: '2-digit', day: '2-digit' }).format(now);
}

function label(date) {
  const noon = new Date(date + 'T12:00:00+09:00');
  const weekday = new Intl.DateTimeFormat('ja-JP', { timeZone: 'Asia/Tokyo', weekday: 'short' }).format(noon);
  const [, month, day] = date.split('-').map(Number);
  return `${month}/${day}（${weekday}）`;
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, file), 'utf8'));
}

function addDays(date, count) {
  const value = new Date(date + 'T12:00:00+09:00');
  value.setUTCDate(value.getUTCDate() + count);
  return tokyoDate(value);
}

const text = (value) => typeof value === 'string' && value.trim() !== '';

// Throws when week.json is not usable; the caller then keeps the previous page.
export function checkWeek(week) {
  if (!week || !Array.isArray(week.days)) throw new Error('week.json has no days');
  for (const row of week.days) {
    if (!row || !DATE.test(row.date)) throw new Error('week.json has a day without a valid date');
    if (row.open && !TIME.test(row.open)) throw new Error(row.date + ': invalid open time');
    if (row.close && !TIME.test(row.close)) throw new Error(row.date + ': invalid close time');
    for (const event of row.events || []) {
      if (!TIME.test(event?.time) || !text(event?.title)) throw new Error(row.date + ': event without a valid time and title');
    }
  }
  return week;
}

// events.json is only used for today; when it does not look right, today comes from week.json.
export function usableEvents(events) {
  if (!events || !DATE.test(events.date) || !Array.isArray(events.events)) return null;
  if (events.open && !TIME.test(events.open)) return null;
  return events.events.every((event) => TIME.test(event?.time) && text(event?.title)) ? events : null;
}

const safeX = (url) => (typeof url === 'string' && /^https:\/\/x\.com\//.test(url) ? url : X_URL);

// One day in a common shape: { date, open, close, closed, ring, games: [{ time, title, prices }] }.
function fromEvents(data) {
  const closed = data.status === 'closed' || !data.open;
  return {
    date: data.date,
    open: data.open || '',
    close: data.close || '',
    closed,
    ring: !closed && !!data.ringGame?.enabled,
    source: safeX(data.schedulePostUrl || data.source?.url),
    games: closed ? [] : (data.events || []).map((event) => ({
      time: event.time,
      title: event.title,
      prices: (event.facts || []).map((fact) => [FACT_LABELS[fact.label] || fact.label, fact.value]),
    })),
  };
}

function fromWeek(week, row) {
  const closed = !row.open;
  return {
    date: row.date,
    open: row.open || '',
    close: row.close || '',
    closed,
    ring: !closed && !!row.ringGame,
    source: safeX(week.sourceUrl),
    games: closed ? [] : (row.events || []).map((event) => ({
      time: event.time,
      title: event.title,
      prices: [['参加費', event.entry], ['再エントリー', event.reentry]].filter(([, value]) => value),
    })),
  };
}

// Today and the next 6 dates; a date with no data is { date, unknown: true }.
export function scheduleDays(week, events, today) {
  const rows = Array.isArray(week?.days) ? week.days : [];
  return Array.from({ length: DAYS_SHOWN }, (_, index) => {
    const date = addDays(today, index);
    if (index === 0 && events?.date === today) return fromEvents(events);
    const row = rows.find((item) => item?.date === date);
    return row ? fromWeek(week, row) : { date, unknown: true };
  });
}

function gameRows(day) {
  return day.games.map((game) => {
    const prices = game.prices.map(([name, value]) => `${escapeHtml(name)} ${escapeHtml(value)}`).join('<br />');
    return `            <tr><th scope="row">${escapeHtml(game.time)}</th><td>${escapeHtml(game.title)}</td><td>${prices || '—'}</td></tr>`;
  }).join('\n');
}

function dayHtml(day, today, promos) {
  const heading = (day.date === today ? '本日 ' : '') + label(day.date);
  if (day.unknown) {
    const tag = day.date === today ? 'h2' : 'h3';
    return `      <section class="day${day.date === today ? ' is-today' : ''}">
        <${tag}><time datetime="${day.date}">${heading}</time></${tag}>
        <p>まだ発表されていません。週間スケジュールは毎週日曜に<a href="${X_URL}" target="_blank" rel="noopener noreferrer">公式X</a>で発表します。</p>
      </section>`;
  }
  const promo = promos.filter((item) => Array.isArray(item.dates) && item.dates.includes(day.date) && item.text)
    .map((item) => `\n        <p class="note">${escapeHtml(item.text)}</p>`).join('');
  if (day.closed) {
    return `      <section class="day${day.date === today ? ' is-today' : ''}">
        <h${day.date === today ? 2 : 3}><time datetime="${day.date}">${heading}</time></h${day.date === today ? 2 : 3}>
        <p>休業日です。</p>${promo}
      </section>`;
  }
  const hours = day.open ? `営業 ${escapeHtml(day.open)}〜${escapeHtml(day.close || '')}` : '';
  const ring = day.ring ? `・NLHリングゲーム（営業時間中）` : '';
  const table = day.games.length ? `
        <table>
          <thead><tr><th scope="col">開始</th><th scope="col">ゲーム</th><th scope="col">料金</th></tr></thead>
          <tbody>
${gameRows(day)}
          </tbody>
        </table>` : `
        <p>トーナメントの予定は掲載されていません。</p>`;
  const tag = day.date === today ? 'h2' : 'h3';
  return `      <section class="day${day.date === today ? ' is-today' : ''}">
        <${tag}><time datetime="${day.date}">${heading}</time></${tag}>
        <p class="hours">${hours}${ring}</p>${table}${promo}
      </section>`;
}

