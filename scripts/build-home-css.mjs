// Builds home.css, the single stylesheet the homepage loads, by joining the
// homepage's CSS files in their original cascade order. One file instead of
// seven means fewer render-blocking requests before the first paint.
//   node scripts/build-home-css.mjs          rebuild home.css and update its ?v= in index.html
//   node scripts/build-home-css.mjs --check  fail if home.css or the ?v= is out of date
// Edit the source files, never home.css itself. Other pages keep linking the
// source files directly.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Same order as the old <link> tags in index.html; later files override earlier ones.
export const SOURCES = ['styles.css', 'v2.css', 'timeline.css', 'activity.css', 'news.css', 'story.css', 'king.css'];
const OUT = 'home.css';
const PAGE = 'index.html';
const LINK = /<link rel="stylesheet" href="\.\/home\.css\?v=[^"]*" \/>/;

function build() {
  const parts = SOURCES.map((name) => {
    const css = fs.readFileSync(path.join(root, name), 'utf8');
    if (/@import|@charset/i.test(css)) throw new Error(`${name}: @import/@charset cannot be bundled`);
    return `/* ---- ${name} ---- */\n${css.trimEnd()}\n`;
  });
  return `/* Generated by scripts/build-home-css.mjs from ${SOURCES.join(', ')}. Do not edit; edit those files and rerun the script. */\n${parts.join('')}`;
}

const css = build();
const version = crypto.createHash('sha256').update(css).digest('hex').slice(0, 10);
const link = `<link rel="stylesheet" href="./home.css?v=${version}" />`;
const pagePath = path.join(root, PAGE);
const page = fs.readFileSync(pagePath, 'utf8');
if (!LINK.test(page)) throw new Error(`${PAGE} has no home.css <link> to update`);

if (process.argv.includes('--check')) {
  const current = fs.existsSync(path.join(root, OUT)) ? fs.readFileSync(path.join(root, OUT), 'utf8') : '';
  const problems = [];
  if (current !== css) problems.push(`${OUT} is out of date`);
  if (!page.includes(link)) problems.push(`${PAGE} does not link ${OUT}?v=${version}`);
  for (const name of SOURCES) if (page.includes(`href="./${name}`)) problems.push(`${PAGE} still links ${name} directly`);
  if (problems.length) {
    console.error(problems.join('\n') + '\nRun: node scripts/build-home-css.mjs');
    process.exit(1);
  }
  console.log(`${OUT} is up to date (v=${version}).`);
} else {
  fs.writeFileSync(path.join(root, OUT), css);
  fs.writeFileSync(pagePath, page.replace(LINK, link));
  console.log(`Wrote ${OUT} (${css.length} bytes, v=${version}).`);
}
