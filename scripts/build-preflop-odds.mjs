// Builds calculator/preflop-odds.js: for each of the 169 starting hands, the exact number of
// 5-card boards (out of C(50,5) = 2,118,760) that give each final hand category by the river.
// Categories: 0 high card ... 8 straight flush, 9 royal flush. Run: node scripts/build-preflop-odds.mjs
import { createRequire } from 'node:module';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import os from 'node:os';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = require(path.join(ROOT, 'calculator/poker-core.js'));
const R = P.RANKS;

function keyOf(hi, lo, suited) { return hi === lo ? R[hi] + R[lo] : R[hi] + R[lo] + (suited ? 's' : 'o'); }

function countFor(hole) {
  const deck = []; for (let c = 0; c < 52; c++) if (!hole.includes(c)) deck.push(c);
  const counts = new Array(10).fill(0); const h = [hole[0], hole[1], 0, 0, 0, 0, 0];
  const n = deck.length;
  for (let a = 0; a < n; a++) { h[2] = deck[a];
    for (let b = a + 1; b < n; b++) { h[3] = deck[b];
      for (let c = b + 1; c < n; c++) { h[4] = deck[c];
        for (let d = c + 1; d < n; d++) { h[5] = deck[d];
          for (let e = d + 1; e < n; e++) { h[6] = deck[e];
            const s = P.evaluate(h); const cat = P.category(s);
            counts[cat === 8 && P.topRank(s) === 12 ? 9 : cat]++;
          } } } } }
  return counts;
}

const hands = [];
for (let hi = 12; hi >= 0; hi--) for (let lo = hi; lo >= 0; lo--) {
  if (hi === lo) hands.push([keyOf(hi, lo), [hi * 4, lo * 4 + 1]]);
  else { hands.push([keyOf(hi, lo, true), [hi * 4, lo * 4]]); hands.push([keyOf(hi, lo, false), [hi * 4, lo * 4 + 1]]); }
}

if (isMainThread) {
  const workers = Math.max(1, os.cpus().length);
  const results = {}; let done = 0; const t0 = Date.now();
  await Promise.all(Array.from({ length: workers }, (_, w) => new Promise((resolve, reject) => {
    const mine = hands.filter((_, i) => i % workers === w);
    const wk = new Worker(new URL(import.meta.url), { workerData: mine });
    wk.on('message', ([k, counts]) => { results[k] = counts; done++; if (done % 20 === 0) console.log(`${done}/169 ${((Date.now() - t0) / 1000).toFixed(0)}s`); });
    wk.on('error', reject); wk.on('exit', resolve);
  })));
  const ordered = {}; hands.forEach(([k]) => { ordered[k] = results[k]; });
  const out = `// Generated by scripts/build-preflop-odds.mjs. Do not edit by hand.\n// Exact counts of final hand categories (0 high card ... 8 straight flush, 9 royal flush) over all C(50,5) = 2118760 boards.\nwindow.PREFLOP_ODDS = { total: 2118760, hands: ${JSON.stringify(ordered)} };\n`;
  fs.writeFileSync(path.join(ROOT, 'calculator/preflop-odds.js'), out);
  console.log(`done in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
} else {
  for (const [k, hole] of workerData) parentPort.postMessage([k, countFor(hole)]);
}
