// Builds calculator/preflop-equity.js: for each of the 169 starting hands, the chance to win
// (equity, ties split) against 1..8 opponents holding random cards, everyone to showdown.
// Monte Carlo, ITER deals per hand and opponent count. Run: node scripts/build-preflop-equity.mjs [iterations]
import { createRequire } from 'node:module';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import os from 'node:os';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = require(path.join(ROOT, 'calculator/poker-core.js'));
const R = P.RANKS;
const ITER = Number(process.argv[2] || workerData?.iter || 200000);

const hands = [];
for (let hi = 12; hi >= 0; hi--) for (let lo = hi; lo >= 0; lo--) {
  if (hi === lo) hands.push([R[hi] + R[lo], [hi * 4, lo * 4 + 1]]);
  else { hands.push([R[hi] + R[lo] + 's', [hi * 4, lo * 4]]); hands.push([R[hi] + R[lo] + 'o', [hi * 4, lo * 4 + 1]]); }
}

if (isMainThread) {
  const workers = Math.max(1, os.cpus().length);
  const results = {}; let done = 0; const t0 = Date.now();
  await Promise.all(Array.from({ length: workers }, (_, w) => new Promise((resolve, reject) => {
    const mine = hands.filter((_, i) => i % workers === w);
    const wk = new Worker(new URL(import.meta.url), { workerData: { mine, iter: ITER } });
    wk.on('message', ([k, eq]) => { results[k] = eq; done++; if (done % 20 === 0) console.log(`${done}/169 ${((Date.now() - t0) / 1000).toFixed(0)}s`); });
    wk.on('error', reject); wk.on('exit', resolve);
  })));
  const ordered = {}; hands.forEach(([k]) => { ordered[k] = results[k]; });
  const out = `// Generated by scripts/build-preflop-equity.mjs (${ITER} deals per value). Do not edit by hand.\n// Equity (win share, ties split) of each starting hand against 1..8 random opponents, everyone to showdown.\nwindow.PREFLOP_EQUITY = { iterations: ${ITER}, hands: ${JSON.stringify(ordered)} };\n`;
  fs.writeFileSync(path.join(ROOT, 'calculator/preflop-equity.js'), out);
  console.log(`done in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
} else {
  for (const [k, hole] of workerData.mine) {
    const eq = [];
    for (let opp = 1; opp <= 8; opp++) {
      const r = P.equityRunner(hole, [], opp + 1); r.step(workerData.iter);
      eq.push(Math.round(r.result().equity * 10000) / 10000);
    }
    parentPort.postMessage([k, eq]);
  }
}
