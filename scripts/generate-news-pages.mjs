function sitemapXml(items) {
  const urls = [
    { loc: SITE },
    { loc: SITE + 'news/' },
    ...items.map((item) => ({
      loc: SITE + 'news/' + safeSegment(item.id) + '/',
      lastmod: item.date,
    })),
  ];
  const body = urls.map(({ loc, lastmod }) =>
    `  <url>\n    <loc>${escapeHtml(loc)}</loc>${lastmod ? `\n    <lastmod>${lastmod}</lastmod>` : ''}\n  </url>`
  ).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
}

function readManifest() {
  try {
    const value = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
    return Array.isArray(value?.ids) ? value.ids.map(safeSegment) : [];
  } catch {
    return [];
  }
}

function writeIfChanged(file, content) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

export function generate(now = Date.now()) {
  const data = JSON.parse(fs.readFileSync(DATA_PATH, 'utf8'));
  core.validateNews(data);
  const visible = core.visibleItems(data, now);
  const ids = visible.map((item) => safeSegment(item.id));
  const previous = readManifest();
  let changed = false;

  for (const id of previous) {
    if (ids.includes(id)) continue;
    const dir = path.join(NEWS_DIR, id);
    const index = path.join(dir, 'index.html');
    if (fs.existsSync(index) && fs.readFileSync(index, 'utf8').includes(GENERATED_MARKER)) {
      fs.rmSync(dir, { recursive: true, force: true });
      changed = true;
    }
  }

  for (const item of visible) {
    const file = path.join(NEWS_DIR, safeSegment(item.id), 'index.html');
    if (writeIfChanged(file, pageHtml(item))) changed = true;
  }

  if (writeIfChanged(SITEMAP_PATH, sitemapXml(visible))) changed = true;
  const manifest = JSON.stringify({ ids }, null, 2) + '\n';
  if (writeIfChanged(MANIFEST_PATH, manifest)) changed = true;

  console.log(`Generated ${visible.length} crawlable NEWS pages; sitemap has ${visible.length + 2} URLs.`);
  return { changed, count: visible.length };
}

if (import.meta.url === new URL('file://' + process.argv[1]).href) generate();
