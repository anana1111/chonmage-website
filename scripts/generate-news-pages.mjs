// The NEWS list is drawn by news/page.js in the browser. The same cards are also written into
// news/index.html between these markers, so crawlers that skip JavaScript still see every link.
const LIST_START = '<!-- news-list:start (generated by scripts/generate-news-pages.mjs) -->';
const LIST_END = '<!-- news-list:end -->';
const CARD_SIZES = '(max-width: 620px) 104px, (max-width: 1000px) 50vw, 33vw';
const COPIED_PHOTO = /^(?:\.\/)?(images\/news\/[A-Za-z0-9_-]+)\.(webp|jpg|png)$/;

// Mirrors ChonmageNewsView.card() in news-view.js, which replaces this markup once the page loads.
function cardHtml(item) {
  const href = safeSegment(item.id) + '/';
  const title = escapeHtml(item.title);
  let visual;
  if (item.image) {
    const copied = item.image.match(COPIED_PHOTO);
    const srcset = copied ? ` srcset="../${copied[1]}-680.${copied[2]} 680w, ${escapeHtml(localImage(item.image).replace(/^\.\.\//, ''))} 1200w" sizes="${CARD_SIZES}"` : '';
    visual = `<a class="news-image news-image--${escapeHtml(item.theme)} news-image--photo" href="${href}" aria-label="${title}を読む"><figure class="news-photo"><img alt="${title}" decoding="async" loading="lazy"${srcset} src="${escapeHtml(localImage(item.image).replace(/^\.\.\//, ''))}" /></figure><span class="news-image-fallback" aria-hidden="true">${escapeHtml(item.visualLabel)}</span></a>`;
  } else {
    visual = `<a class="news-image news-image--${escapeHtml(item.theme)}" href="${href}" aria-label="${title}を読む"><span class="news-image-category">${escapeHtml(item.category)}</span><strong>${escapeHtml(item.visualLabel)}</strong><span class="news-image-arrow" aria-hidden="true">→</span></a>`;
  }
  return `        <article class="news-card">${visual}<div class="news-meta"><time datetime="${escapeHtml(item.publishedAt)}">${escapeHtml(item.date.replaceAll('-', '.'))}</time><span>${escapeHtml(item.category)}</span></div><h3><a href="${href}">${title}</a></h3><p class="news-summary">${escapeHtml(item.summary)}</p></article>`;
}

function listHtml(items) {
  const cards = items.length ? items.map(cardHtml).join('\n') : '        <p class="news-empty">最近30日間のニュースはありません。</p>';
  return `${LIST_START}
      <h1 class="news-page-title">NEWS</h1>
      <p class="news-page-lead">ちょんまげから、最近30日間のお知らせ。</p>
      <div class="news-grid">
${cards}
      </div>
      ${LIST_END}`;
}

function withList(html, items) {
  const start = html.indexOf(LIST_START);
  const end = html.indexOf(LIST_END);
  if (start < 0 || end < start) throw new Error('news/index.html is missing the news-list markers');
  return html.slice(0, start) + listHtml(items) + html.slice(end + LIST_END.length);
}

function sitemapXml(items) {
  const urls = [
    { loc: SITE },
    { loc: SITE + 'news/' },
    { loc: SITE + 'company/' },
    { loc: SITE + 'faq/' },
    { loc: SITE + 'beginner/' },
    { loc: SITE + 'king/' },
    ...items.map((item) => ({
      loc: SITE + 'news/' + safeSegment(item.id) + '/',
      lastmod: item.date,
    })),
  ];
  const body = urls.map(({ loc, lastmod }) =>
    `  <url>\n    <loc>${escapeHtml(loc)}</loc>${lastmod ? `\n    <lastmod>${lastmod}</lastmod>` : ''}\n  </url>`
  ).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
}

function readManifest() {
  try {
    const value = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
    return Array.isArray(value?.ids) ? value.ids.map(safeSegment) : [];
  } catch {
    return [];
  }
}

function writeIfChanged(file, content) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

export function generate(now = Date.now()) {
  const data = JSON.parse(fs.readFileSync(DATA_PATH, 'utf8'));
  core.validateNews(data);
  const visible = core.visibleItems(data, now);
  const ids = visible.map((item) => safeSegment(item.id));
  const previous = readManifest();
  let changed = false;

  for (const id of previous) {
    if (ids.includes(id)) continue;
    const dir = path.join(NEWS_DIR, id);
    const index = path.join(dir, 'index.html');
    if (fs.existsSync(index) && fs.readFileSync(index, 'utf8').includes(GENERATED_MARKER)) {
      fs.rmSync(dir, { recursive: true, force: true });
      changed = true;
    }
  }

  for (const item of visible) {
    const file = path.join(NEWS_DIR, safeSegment(item.id), 'index.html');
    if (writeIfChanged(file, pageHtml(item))) changed = true;
  }

  const listPath = path.join(NEWS_DIR, 'index.html');
  if (writeIfChanged(listPath, withList(fs.readFileSync(listPath, 'utf8'), visible))) changed = true;
  if (writeIfChanged(SITEMAP_PATH, sitemapXml(visible))) changed = true;
  const manifest = JSON.stringify({ ids }, null, 2) + '\n';
  if (writeIfChanged(MANIFEST_PATH, manifest)) changed = true;

  console.log(`Generated ${visible.length} crawlable NEWS pages; sitemap has ${visible.length + 6} URLs.`);
  return { changed, count: visible.length };
}

if (import.meta.url === new URL('file://' + process.argv[1]).href) generate();
