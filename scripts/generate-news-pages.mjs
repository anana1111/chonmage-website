// Generate crawlable static NEWS detail pages and sitemap entries from data/news.json.
// The public NEWS list still shows the most recent 30 days; generated detail pages follow
// the same visibility rule so drafts, scheduled posts and expired posts are never exposed.
import fs from 'node:fs';
import path from 'node:path';
import '../news-core.js';

const core = globalThis.ChonmageNews;
const ROOT = process.cwd();
const DATA_PATH = path.join(ROOT, 'data', 'news.json');
const MANIFEST_PATH = path.join(ROOT, 'data', 'news-pages.generated.json');
const NEWS_DIR = path.join(ROOT, 'news');
const SITEMAP_PATH = path.join(ROOT, 'sitemap.xml');
const SITE = 'https://chonmagepoker.com/';
const FALLBACK_IMAGE = SITE + 'images/og-image.jpg?v=2';
const GENERATED_MARKER = '<!-- generated by scripts/generate-news-pages.mjs -->';

function escapeHtml(value = '') {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function escapeJsonForHtml(value) {
  return JSON.stringify(value, null, 2).replaceAll('<', '\\u003c');
}

function safeSegment(value) {
  const segment = String(value || '').trim();
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]{0,199}$/.test(segment)) {
    throw new Error('Unsafe NEWS id for static path: ' + JSON.stringify(value));
  }
  return segment;
}

function absoluteImage(value) {
  if (!value) return FALLBACK_IMAGE;
  if (/^https:\/\//i.test(value)) return value;
  return new URL(value.replace(/^\.\//, ''), SITE).href;
}

function localImage(value) {
  if (!value) return '';
  if (/^https:\/\//i.test(value)) return value;
  return '../../' + value.replace(/^\.\//, '');
}

