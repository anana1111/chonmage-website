  const photos = (item.images || []).map((url, index) => {
    const alt = item.title + (index ? '（' + (index + 1) + '）' : '');
    return `      <figure class="news-photo"><img src="${escapeHtml(localImage(url))}" alt="${escapeHtml(alt)}" decoding="async" loading="${index === 0 ? 'eager' : 'lazy'}" /></figure>`;
  }).join('\n');

  const sourceButton = item.source === 'x' && item.sourceUrl && item.sourceUnavailable !== true
    ? `      <a class="news-button news-source" href="${escapeHtml(item.sourceUrl)}" target="_blank" rel="noopener noreferrer">Xで元の投稿を見る</a>`
    : '';

